/* ---- MCU registers (PY32F071, core and SysTick at 48 MHz, 10 ms period) ----
 * The ADC and DAC registers are reached from one base per block: the base goes
 * through an empty asm, so GCC addresses them as [base, #offset] from one
 * literal-pool word instead of one word per register address. */
static inline volatile uint32_t *hw(uint32_t a){
    volatile uint32_t *p=(volatile uint32_t *)a;
    __asm__("" : "+l"(p));
    return p;
}
#define SYST_LOAD   (*(volatile uint32_t *)0xE000E014u)
#define SYST_VAL    (*(volatile uint32_t *)0xE000E018u)
#define ADC_SR      (hw(0x40012400u)[0x00/4])
#define ADC_CR2     (hw(0x40012400u)[0x08/4])
#define ADC_SMPR3   (hw(0x40012400u)[0x14/4])
#define ADC_SQR3    (hw(0x40012400u)[0x38/4])
#define ADC_DR      (hw(0x40012400u)[0x50/4])
#define GPIOA_MODER (*(volatile uint32_t *)0x50000000u)
#define DAC_CR      (hw(0x40007400u)[0x00/4])
#define DAC_SWTRIGR (hw(0x40007400u)[0x04/4])
#define DAC_DHR12R1 (hw(0x40007400u)[0x08/4])
#define RCC_APBENR1 (*(volatile uint32_t *)0x4002103Cu)
#define RCC_DACEN   (1u << 29)
/* DAC channel 1 on, output buffer off, software trigger (TSEL1 = 111) */
#define DAC_CR_BIAS ((1u << 0) | (1u << 1) | (1u << 2) | (7u << 3))
#define BIAS_CODE   2048u
#define ADC_SR_EOC     (1u << 1)
#define ADC_CR2_START  ((1u << 22) | (1u << 20))   /* SWSTART | EXTTRIG */
#define SMP8_POS       24u
#define SMP4_POS       12u
#define ADC_CH_PA4     4u
#define FS             9600u
#define CYC_PER_SAMPLE (48000000u / FS)            /* 5000 */
#define HOUSE_EVERY    480u    /* samples between key/screen slots (50 ms)       */
#define BUSY_MAX       40u     /* serve them anyway after 40 busy slots (2 s)    */
#define REFRESH_SLOTS  100u    /* 100 housekeeping slots = 5 s (battery, age)    */
#define REDRAW_ON      1u      /* g.redraw: a key or the periodic refresh        */
#define REDRAW_FRAME   2u      /* g.redraw: a page, also wakes the backlight     */
#define DUP_SAMPLES    128u    /* address codewords this close (half a codeword
                                  of 256 samples) are the same page, read by
                                  another slicer                                 */

/* ---- BK4829 RAW receive (EPIRB 406) ---- */
#define REG_2B      0x2B   /* <10:8> = 1: RX HPF300, LPF3K, de-emphasis off  */
#define REG_73      0x73   /* <4> = 1: AFC off (it would follow the bits)    */

/* ---- demodulator (test/model_rx.py, class Demod) ---- */
#define PLL_STEP    8192   /* 65536 per bit / 8 samples per bit             */
#define PLL_CTR     36864  /* transitions pulled to mid-bit + half a sample */
#define PLL_SHIFT   3      /* 1/8 of the error per transition               */
#define NSL         5      /* slicers: see SL_K / SL_N                      */
#define DIRTY_WORDS 8u     /* codewords a slicer is not trusted to correct
                              after a bad one                               */

/* ---- POCSAG (test/pocsag.py) ---- */
#define SYNC        0x7CD215D8u
#define IDLE        0x7A89C197u
#define GEN         0x769u /* BCH (31,21): x^10 + x^9 + x^8 + x^6 + x^5 + x^3 + 1 */
#define SYNC_ERR    2u     /* wrong bits tolerated in a sync codeword       */
#define BATCH_WORDS 16u
#define HUNT        0xFFu  /* sl_t.word: looking for the sync codeword      */
#define FUNC_NUMERIC 0u    /* by usage: function 0 numeric, the others text */
#define MSG_MAX     80u    /* characters kept per page (DAPNET: 80)         */
#define HISTORY     5u

typedef struct {
    uint32_t ric;                      /* 21-bit address                          */
    uint32_t t;                        /* ticks_ms when received                  */
    uint32_t at;                       /* sample its address codeword came at     */
    int16_t  rssi;
    uint8_t  func, len;
    char     text[MSG_MAX];
} page_t;

/* one slicer: its decision, DPLL, batch decoder, the page being read */
typedef struct {
    int32_t  fb, amp;                  /* feedback: restored baseline, mean |r| (both
                                          Q4); hysteresis: amp = peak of |y|      */
    int32_t  rprev, phase;             /* last r, DPLL phase (65536/bit)          */
    uint32_t sr;                       /* the last 32 bits, the newest in bit 0   */
    uint32_t inv;                      /* polarity found at the sync codeword     */
    uint32_t ric;
    uint32_t at;                       /* sample the address of the page came at  */
    uint8_t  k;                        /* feedback: fb follows 1/2^k              */
    uint8_t  num;                      /* hysteresis: thresholds at num/8 of the peak;
                                          0 = a feedback slicer                   */
    uint8_t  dirty;                    /* codewords left before a correction is
                                          trusted again                           */
    uint8_t  nb;                       /* bits of the codeword being read         */
    uint8_t  word;                     /* codeword of the batch, 16 = the next sync,
                                          HUNT = no batch                         */
    uint8_t  has;                      /* an address was read: a page is open     */
    uint8_t  func, len;
    uint8_t  acc, na;                  /* character being assembled, its bits     */
    char     text[MSG_MAX];
} sl_t;

/* The app state in one struct: a function loads one base address instead of one
 * literal-pool word per global. Bytes, then halfwords, then words. The loader
 * zeroes the overlay (.bss) at every launch. */
